// Generates the built-in exercise library migration from supabase/seed-data/exercises.json.
//   node scripts/build-exercise-seed.mjs
// The JSON is the source of truth; commit both. Validation lives in src/exercises/seed.test.ts.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const input = join(root, 'supabase/seed-data/exercises.json');
const output = join(root, 'supabase/migrations/20260929120100_exercise_seed.sql');

const rows = JSON.parse(readFileSync(input, 'utf8'));

const lit = (s) => (s === null || s === undefined ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => (a.length ? `array[${a.map(lit).join(', ')}]` : `'{}'::text[]`);

const values = rows
  .map(
    (e) =>
      `  (${lit(e.name)}, ${lit(e.primary_muscle)}, ${arr(e.secondary_muscles)}, ${lit(e.equipment)}, ` +
      `${lit(e.tracking_type)}, ${lit(JSON.stringify(e.instructions))}::jsonb)`,
  )
  .join(',\n');

const sql = `-- Step 2: the built-in exercise library (owner_id null = read-only to users).
-- GENERATED by scripts/build-exercise-seed.mjs from supabase/seed-data/exercises.json. Do not edit.
-- Names, muscles and equipment curated from free-exercise-db (Unlicense); instructions are original.
-- Re-running skips names that already exist (exercises_owner_name_key).

insert into public.exercises
  (name, primary_muscle, secondary_muscles, equipment, tracking_type, instructions)
values
${values}
on conflict (owner_id, lower(name)) do nothing;
`;

writeFileSync(output, sql);
console.log(`Wrote ${rows.length} exercises to ${output.replace(root + '/', '')}`);

// The seed above predates movement slots, so they arrive as an update (the seed insert skips
// names that exist). The column comes from 20261008120000_exercise_movement_pattern.sql.
const slotOutput = join(
  root,
  'supabase/migrations/20261008120100_exercise_movement_pattern_data.sql',
);
const slotValues = rows.map((e) => `  (${lit(e.name)}, ${lit(e.movement_pattern)})`).join(',\n');
writeFileSync(
  slotOutput,
  `-- Tags the built-in library with movement slots.
-- GENERATED by scripts/build-exercise-seed.mjs from supabase/seed-data/exercises.json. Do not edit.
update public.exercises e
set movement_pattern = v.movement_pattern
from (values
${slotValues}
) as v (name, movement_pattern)
where e.owner_id is null and lower(e.name) = lower(v.name);
`,
);
console.log(`Wrote movement slots to ${slotOutput.replace(root + '/', '')}`);
