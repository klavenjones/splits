// Generates the default lift templates migration from supabase/seed-data/default-templates.json.
//   node scripts/build-default-templates.mjs
// The JSON is the source of truth; commit both. Validation lives in src/templates/defaultTemplates.test.ts.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const input = join(root, 'supabase/seed-data/default-templates.json');
const output = join(root, 'supabase/migrations/20261019120000_default_templates.sql');

const templates = JSON.parse(readFileSync(input, 'utf8'));
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

const sql = `-- Default lift templates: every user gets their own editable copy (no schema change).
-- GENERATED by scripts/build-default-templates.mjs from supabase/seed-data/default-templates.json. Do not edit.
-- Source: the "Hybrid Plan" and "All Movements Plan" sheets (lift Mon / Wed / Fri, run Tue / Thu / Sat).

-- Copies the defaults into one user's library. Skips a template the user already has by name, so
-- it is safe to call again. Raises if an exercise name doesn't match a built-in.
create or replace function public.seed_default_templates(p_user uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_defaults jsonb := ${lit(JSON.stringify(templates, null, 2))}::jsonb;
  v_t jsonb;
  v_e jsonb;
  v_template uuid;
  v_exercise uuid;
  v_position int;
begin
  for v_t in select * from jsonb_array_elements(v_defaults) loop
    continue when exists (
      select 1 from public.templates
      where user_id = p_user and lower(name) = lower(v_t->>'name')
    );

    insert into public.templates (user_id, name, kind, notes, est_duration_s)
    values (p_user, v_t->>'name', 'lift', v_t->>'notes', (v_t->>'est_duration_s')::int)
    returning id into v_template;

    v_position := 0;
    for v_e in select * from jsonb_array_elements(v_t->'exercises') loop
      select id into v_exercise from public.exercises
      where owner_id is null and lower(name) = lower(v_e->>'exercise');
      if v_exercise is null then
        raise exception 'default template %: no built-in exercise %', v_t->>'name', v_e->>'exercise';
      end if;

      insert into public.template_exercises
        (template_id, exercise_id, position, target_sets, rep_min, rep_max, rest_sec, notes)
      values (
        v_template, v_exercise, v_position, (v_e->>'target_sets')::int, (v_e->>'rep_min')::int,
        (v_e->>'rep_max')::int, (v_e->>'rest_sec')::int, v_e->>'notes'
      );
      v_position := v_position + 1;
    end loop;
  end loop;
end;
$$;

revoke execute on function public.seed_default_templates(uuid) from public, anon, authenticated;

-- New accounts get the defaults at sign-up.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.users (id) values (new.id) on conflict (id) do nothing;
  perform public.seed_default_templates(new.id);
  return new;
end;
$$;

revoke execute on function public.handle_new_user() from public, anon, authenticated;

-- Backfill existing accounts.
select public.seed_default_templates(id) from public.users;
`;

writeFileSync(output, sql);
console.log(`Wrote ${templates.length} default templates to ${output.replace(root + '/', '')}`);
