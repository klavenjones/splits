// Generates the migration that attaches wger illustrations to built-in exercises.
//   node scripts/build-exercise-media-migration.mjs
// Source: supabase/seed-data/wger-images.json (from scripts/wger-images.mjs). Upload the files to
// exercise-media/builtin/ first (see supabase/seed-data/README.md). Commit both.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const input = join(root, 'supabase/seed-data/wger-images.json');
const output = join(root, 'supabase/migrations/20260930120000_exercise_media_credit.sql');

const rows = JSON.parse(readFileSync(input, 'utf8'));
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

const values = rows
  .map((e) => `  (${lit(e.name)}, ${lit(e.file)}, ${lit(JSON.stringify(e.credit))}::jsonb)`)
  .join(',\n');

const sql = `-- Step 2b: demo illustrations for built-in exercises, with the credit their license requires.
-- GENERATED by scripts/build-exercise-media-migration.mjs from supabase/seed-data/wger-images.json.
-- Images: Everkinetic / wger.de line art via wger (CC-BY-SA), stored unmodified in
-- exercise-media/builtin/.

-- { author, author_url?, license, license_url, source_url } for third-party media; null otherwise.
alter table public.exercises
  add column if not exists media_credit jsonb
  check (media_credit is null or jsonb_typeof(media_credit) = 'object');

-- Every signed-in user can read built-in media. Nobody but the service role writes there: the
-- insert/update/delete policies only match a folder named after the caller's own user id.
create policy "exercise-media: read built-in" on storage.objects
  for select to authenticated
  using (bucket_id = 'exercise-media' and (storage.foldername(name))[1] = 'builtin');

update public.exercises e
set thumbnail_url = v.path, media_credit = v.credit
from (values
${values}
) as v (name, path, credit)
where e.owner_id is null and e.name = v.name;
`;

writeFileSync(output, sql);
console.log(`Wrote ${rows.length} exercise images to ${output.replace(root + '/', '')}`);
